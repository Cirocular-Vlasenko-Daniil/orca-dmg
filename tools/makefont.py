REVERSE_FIELD = 2   # the block an output port is painted on
REVERSE_INK = 0     # ...with the glyph knocked out of it


def shade(ch):
    if ch == '.':
        return 1
    if ch.isdigit() or ('a' <= ch <= 'z'):
        return 2
    return 3


def tile_bytes(ch, reverse=False):
    """Glyph occupies cols 1..5, rows 0..6 of the 8x8 tile."""
    rows = G.get(ch)
    ink = REVERSE_INK if reverse else (shade(ch) if rows else 3)
    field = REVERSE_FIELD if reverse else 0
    out = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            on = (rows is not None and y < 7 and 1 <= x <= 5
                  and rows[y][x - 1] == '#')
            col = ink if on else field
            if col & 1:
                lo |= 1 << (7 - x)
            if col & 2:
                hi |= 1 << (7 - x)
        out.append(lo)
        out.append(hi)
    return out


# An empty input port: bigger and brighter than a grid dot, so the cells an
# operator still wants filling read as holes rather than as background.
PORT_DOT = ('.....',
            '.....',
            '.###.',
            '.#.#.',
            '.###.',
            '.....',
            '.....')


def port_dot_tile():
    out = []
    for y in range(8):
        lo = hi = 0
        if y < 7:
            for x in range(5):
                if PORT_DOT[y][x] == '#':
                    lo |= 1 << (7 - (x + 1))
                    hi |= 1 << (7 - (x + 1))
        out.append(lo)
        out.append(hi)
    return out


# --- cursor sprite: corner brackets, colour 3 -------------------------------
CURSOR = ('##...##',
          '#.....#',
          '.......',
          '.......',
          '.......',
          '#.....#',
          '##...##')


def cursor_tile():
    out = []
    for y in range(8):
        lo = hi = 0
        if y < 7:
            for x in range(7):
                if CURSOR[y][x] == '#':
                    lo |= 1 << (7 - x)
                    hi |= 1 << (7 - x)
        out.append(lo)
        out.append(hi)
    return out


def emit(f, name, data, per_line=16):
    f.write("const unsigned char %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), per_line):
        f.write("    " + ",".join("0x%02X" % b for b in data[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    tiles = []
    for c in range(0x20, 0x80):
        tiles += tile_bytes(chr(c))
    for c in range(0x20, 0x80):
        tiles += tile_bytes(chr(c), reverse=True)
    tiles += port_dot_tile()
    with open(sys.argv[1], 'w') as f:
        f.write("/* generated by tools/makefont.py -- do not edit */\n\n")
        f.write("#pragma bank 1\n\n")
        emit(f, "font_tiles", tiles)
        emit(f, "cursor_tile_data", cursor_tile())
    print("%s: %d tiles (%d bytes)" % (sys.argv[1], len(tiles) // 16, len(tiles)))


main()
